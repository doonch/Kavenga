/**
 * Declarative configurations for Optional 3D Walkable Shore Mode in Kavenga: Songs of the Star Path.
 *
 * All 17 islands default to the Unified 3D Shore Diorama Stage (`ShoreDioramaRenderer` + `IslandHubUI`).
 * On these 4 showcase islands, players may optionally click `Walk Ashore` to walk directly upon
 * the EXACT canonical 3D island mesh (`IslandTerrainBuilder`) seen from the ocean & map room:
 *  - `raiatea`  ("Sacred High Island" — Act I opening & return consecration island)
 *  - `tahaa`    ("Sheltered Lagoon Isle" — Act I clover-leaf bay, Hina & Fisher Tama)
 *  - `hawaii`   ("Ancestral Mauna Horizon" — Act III snow-crowned & lava-lit Grand Finale)
 *  - `rapa_nui` ("Te Pito o Te Henua" — Secret uninhabited Moai monolith island)
 *
 * Strictly zero cardinal directions or degree numbers in all player-facing copy.
 */

export const WALKABLE_ISLAND_IDS = Object.freeze(
  new Set(['raiatea', 'tahaa', 'hawaii', 'rapa_nui'])
);

export function isWalkableIsland(islandId) {
  return WALKABLE_ISLAND_IDS.has(islandId);
}

export function canWalkIsland(islandId) {
  return Boolean(WALKABLE_ISLAND_SPECS[islandId]);
}

function makeStandardWalkableSpec({
  islandId,
  canonicalScale,
  gridHalfSpan,
  gridN,
  solarHourBase = 9.25,
  canoe,
  spawn,
  landing,
  hut,
  circle,
  elder,
  landingLabel = 'Canoe Landing',
  hutLabel = "Craftsmen's & Ration Hut",
  hutTitle = "Provisioning & Canoe-Wrights' Hut",
  craftsmanName = 'Island Boatbuilder',
  craftsmanQuote = 'Fresh coconut fiber, sweet water gourds, and dried bonito are ready beneath the thatch whenever your hulls need careening.',
  isWildShelter = false,
  circleLabel = "Navigator's Sand Ring",
  circleTitle = "Navigator's Observation Ring & Teaching Sand",
  elderLabel = 'Sanctuary & Marae',
  elderTitle = 'Island Sanctuary & Marae',
  elderSubtitle = 'Speak with the local wayfinder elder, trade island gifts, and learn the next chant',
  elderPrompt = 'Speak with Island Elder',
  elderGlyph = '🌺',
  extraPois = [],
}) {
  const arrivalFor = (pt, facingYawRad, camYawRad) => {
    const dx = spawn.x - pt.x;
    const dz = spawn.z - pt.z;
    const len = Math.hypot(dx, dz) || 1.0;
    const step = Math.min(2.4, len * 0.4);
    return Object.freeze({
      x: Number((pt.x + (dx / len) * step).toFixed(1)),
      z: Number((pt.z + (dz / len) * step).toFixed(1)),
      facingYawRad,
      camYawRad,
    });
  };

  return Object.freeze({
    islandId,
    ...(canonicalScale !== undefined ? { canonicalScale } : {}),
    ...(gridHalfSpan !== undefined ? { gridHalfSpan } : {}),
    ...(gridN !== undefined ? { gridN } : {}),
    walkSpeedMps: 6.8,
    sprintSpeedMps: 9.4,
    solarHourBase,
    initialSpawn: Object.freeze({
      x: spawn.x,
      z: spawn.z,
      facingYawRad: -0.38,
      camYawRad: 0.24,
    }),
    vigilExitSpawn: Object.freeze({
      x: Number((circle.x + 1.8).toFixed(1)),
      z: Number((circle.z + 2.6).toFixed(1)),
      facingYawRad: 0.0,
    }),
    mooredCanoe: Object.freeze({
      x: canoe.x,
      z: canoe.z,
      yawRad: 2.54,
    }),
    pois: Object.freeze([
      Object.freeze({
        id: 'canoe_landing',
        kind: 'canoe',
        hubTab: 'landing',
        glyph: '🛶',
        label: landingLabel,
        title: `Moored Voyaging Canoe — ${landingLabel}`,
        subtitle: 'Inspect readiness, choose your route chant & tide-light, and set sail',
        promptHint: 'Board Canoe & Set Sail',
        x: landing.x,
        z: landing.z,
        triggerRadiusM: 4.8,
        markerRadiusM: 3.1,
        arrivalSpot: arrivalFor(landing, 2.31, 2.15),
      }),
      Object.freeze({
        id: 'provisioning_hut',
        kind: 'hut',
        hubTab: 'landing',
        glyph: '🛖',
        label: hutLabel,
        title: hutTitle,
        subtitle: isWildShelter
          ? 'Gather fresh coconuts & clear lagoon water along the wild shore'
          : 'Refill woven ration baskets, careen hulls, and speak with local artisans',
        promptHint: isWildShelter ? 'Forage Rations & Inspect Camp' : 'Refill Rations & Speak to Artisans',
        isWildShelter,
        craftsmanName,
        craftsmanQuote,
        x: hut.x,
        z: hut.z,
        triggerRadiusM: 5.8,
        markerRadiusM: 3.8,
        arrivalSpot: arrivalFor(hut, 0.31, 0.38),
      }),
      Object.freeze({
        id: 'observation_circle',
        kind: 'circle',
        hubTab: 'sand',
        glyph: '🐚',
        label: circleLabel,
        title: circleTitle,
        subtitle: 'Trace stick-in-the-sand lessons or enter the Night-Sky Star-Stone Vigil',
        promptHint: 'Study Teaching Sand & Sky Circle',
        circleDesc:
          'From this breezy stone ring overlooking the lagoon and open horizon, wayfinders trace wave, cloud, and star-path lessons in swept coral sand.',
        x: circle.x,
        z: circle.z,
        triggerRadiusM: 5.8,
        markerRadiusM: 3.8,
        arrivalSpot: arrivalFor(circle, 0.05, 0.08),
      }),
      Object.freeze({
        id: 'elder_marae',
        kind: 'elder',
        hubTab: 'sanctuary',
        glyph: elderGlyph,
        label: elderLabel,
        title: elderTitle,
        subtitle: elderSubtitle,
        promptHint: elderPrompt,
        x: elder.x,
        z: elder.z,
        triggerRadiusM: 6.2,
        markerRadiusM: 4.2,
        arrivalSpot: arrivalFor(elder, -1.82, -1.75),
      }),
      ...extraPois.map((ep) =>
        Object.freeze({
          ...ep,
          arrivalSpot: ep.arrivalSpot || arrivalFor(ep, -1.0, -1.0),
        })
      ),
    ]),
  });
}

